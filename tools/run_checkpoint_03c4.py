#!/usr/bin/env python
"""Run Checkpoint 03C.4 leakage-safe nested stacking evaluation."""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from geocebada.evaluation import (
    build_competition_representation_specs,
    evaluate_nested_stacking,
    summarize_stacking_results,
)
from geocebada.features import join_agronomic_features, join_empirical_features
